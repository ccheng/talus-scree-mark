import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const app = new URL('../app/', import.meta.url);
const index = new URL('index.html', app);
const precache = new URL('precache.generated.js', app);
const staticFiles = [
  'assets/icon-180.png',
  'assets/icon-192.png',
  'assets/icon-512.png',
  ...['interleaved', 'mc-only', 'mixed'].flatMap((variant) =>
    ['blank.png', 'filled.png', 'blank.pdf', 'filled.pdf', 'key.json'].map((file) => `fixtures/m3/${variant}-${file}`)),
  'index.html',
  'manifest.webmanifest',
  'reference/profile.js',
  'reference/profile.json',
  'reference/profile.sha256',
  'reference/reference-blank.pdf',
  'reference/reference-filled.pdf',
  'reference/reference-filled.png',
  'reference/reference-key.json',
  'src/camera.js',
  'src/grading.js',
  'src/grading-store.js',
  'src/grading-export.js',
  'src/grading-view.js',
  'src/image.js',
  'src/layout-discovery.js',
  'src/bubble-registration.js',
  'src/main.js',
  'src/markerless-registration.js',
  'src/offline.js',
  'src/marks.js',
  'src/omr.js',
  'src/omr-image.js',
  'src/omr-worker.js',
  'src/profile-authoring.js',
  'src/profile-editor.js',
  'src/profile-omr.js',
  'src/profile-store.js',
  'src/profile-workspace.js',
  'src/projective.js',
  'src/recognition-view.js',
  'src/reference-contract.js',
  'src/registration.js',
  'styles.css',
];
const releaseTag = /(<meta name="scree-release" content=")[^"]+(")/;
const indexSource = await readFile(index, 'utf8');
if (!releaseTag.test(indexSource)) throw new Error('index.html needs a scree-release meta tag.');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

const assets = new Map(await Promise.all(staticFiles.map(async (file) => [
  file,
  file === 'index.html'
    ? indexSource.replace(releaseTag, '$1release-template$2')
    : await readFile(new URL(file, app)),
])));
const inputs = Object.fromEntries([...assets].map(([file, value]) => [file, sha256(value)]));
inputs['sw.js'] = sha256(await readFile(new URL('sw.js', app)));
const releaseId = sha256(JSON.stringify(inputs)).slice(0, 24);
const outputIndex = indexSource.replace(releaseTag, (_tag, before, after) => before + releaseId + after);
const { 'sw.js': _workerDigest, ...shellAssets } = inputs;
shellAssets['index.html'] = sha256(outputIndex);
const outputPrecache = `// Generated by npm run build.\nexport const releaseId = ${JSON.stringify(releaseId)};\nexport const shellAssets = ${JSON.stringify(shellAssets, null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (indexSource !== outputIndex || await readFile(precache, 'utf8') !== outputPrecache) {
    throw new Error('Release metadata is stale. Run npm run build.');
  }
} else {
  await writeFile(index, outputIndex);
  await writeFile(precache, outputPrecache);
}
console.log(`Shell release ${releaseId}`);
